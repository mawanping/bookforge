"""bookforge · 把网站文章变成电子书。

核心设计原则（决定了它为什么能在各种 agent 里通用）：

1. **纯 Python，零 LLM 依赖** —— 抓取、提取、分组、排版、打包全部是确定性代码。
   唯一的可选 LLM 环节是「翻译」和「AI 封面底图」，都不做也能出成品。
   这意味着 token 消耗与站点规模无关：700 篇和 7 篇花费一样多。
2. **单命令入口** —— ``bookforge build <网址>`` 跑完全程。
   agent 只需要记住一条命令，不需要理解内部阶段。
3. **机器可读的产物** —— 每次构建都产出 ``reports/summary.json``，
   agent 读 20 行 JSON 就能判断成败，不必翻阅几千行日志。
4. **归档包规范** —— 所有阶段围绕同一套目录约定读写，
   任何一步都可以单独重跑、断点续传。
"""

